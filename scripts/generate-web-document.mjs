#!/usr/bin/env node

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const templatePath = resolve(root, 'assets/index.html');
const bundlePath = resolve(root, 'assets/seatlayer.js');
const outputPath = resolve(root, 'src/generated/webDocument.ts');
const marker = '/*__SEATLAYER_BUNDLE__*/';

const template = readFileSync(templatePath, 'utf8');
if (!template.includes(marker)) {
  throw new Error(`Missing ${marker} in ${templatePath}`);
}

const bundle = readFileSync(bundlePath, 'utf8')
  .replaceAll('</script', '<\\/script');
const document = template.replace(marker, bundle);
const source = [
  '// Generated by scripts/generate-web-document.mjs. Do not edit.',
  `export const seatLayerWebDocument = ${JSON.stringify(document)};`,
  '',
].join('\n');

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, source);
console.log(`Generated ${outputPath} (${Buffer.byteLength(document)} bytes HTML)`);
